<?php

declare(strict_types=1);

namespace App\Http\Controllers\Accounting;

use App\Models\AccountingAccount;
use App\Models\JournalEntry;
use App\Models\User;
use App\Services\AccountingPostService;
use App\Services\Audit;
use App\Support\Atelier;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\Rule;
use Illuminate\View\View;

/**
 * General accounting (Finance & Comptabilité spec v1.3 §6, SYSCOHADA).
 *
 * GET /accounting/general — chart of accounts (plan comptable), the
 * journal listing and the manual-entry form (Comptable only).
 * GET /accounting/ledger/{id} — grand livre of one account.
 * GET /accounting/balance — trial balance (balance des comptes).
 * POST /accounting/general/entry — manual OD entry (Comptable, §6).
 * POST /accounting/general/generate — retroactive generation from
 * history (guarded, idempotent).
 *
 * Entries generated by operations are read-only; the app's philosophy
 * (§6) is that the user never types an account — the compact SYSCOHADA
 * mapping lives in AccountingPostService and must be validated by a
 * professional accountant before official use.
 */
class GeneralAccountingController
{
    /** Journal entries per page. */
    private const PER_PAGE = 25;

    /**
     * GET /accounting/general — plan comptable + journal + manual form.
     */
    public function index(Request $request): View
    {
        $journal = (string) ($request->query('journal') ?? '');

        $entries = JournalEntry::query()
            ->with(['lines.account:id,code,name'])
            ->orderByDesc('entry_date')
            ->orderByDesc('created_at');

        if ($journal !== '' && in_array($journal, Atelier::JOURNALS, true)) {
            $entries->where('journal', $journal);
        }

        return view('accounting.general.index', [
            'accounts' => AccountingAccount::query()->orderBy('code')->get(),
            'entries' => $entries->paginate(self::PER_PAGE)->withQueryString(),
            'journals' => Atelier::JOURNALS,
            'filters' => ['journal' => $journal],
        ]);
    }

    /**
     * POST /accounting/general/entry — manual OD entry (Comptable, §6)
     * for diverse operations and corrections. Lines arrive as parallel
     * arrays (code[], debit[], credit[]) from the repeating form.
     */
    public function storeEntry(Request $request): RedirectResponse
    {
        $data = $request->validate([
            'date' => ['required', 'date'],
            'description' => ['required', 'string', 'min:3', 'max:300'],
            'reference' => ['nullable', 'string', 'max:60'],
            'code' => ['required', 'array', 'min:2'],
            'code.*' => ['required', 'string', 'exists:accounting_accounts,code'],
            'debit' => ['required', 'array'],
            'debit.*' => ['nullable', 'numeric', 'min:0'],
            'credit' => ['required', 'array'],
            'credit.*' => ['nullable', 'numeric', 'min:0'],
        ]);

        /** @var User $me */
        $me = $request->user();

        $lines = [];
        foreach ($data['code'] as $i => $code) {
            $debit = (float) ($data['debit'][$i] ?? 0);
            $credit = (float) ($data['credit'][$i] ?? 0);

            if ($debit <= 0 && $credit <= 0) {
                continue; // skip empty rows
            }

            $lines[] = [
                'code' => $code,
                'label' => null,
                'debit' => $debit,
                'credit' => $credit,
            ];
        }

        try {
            $entry = AccountingPostService::manualEntry(
                \Carbon\Carbon::parse($data['date']),
                $data['description'],
                $lines,
                $me,
                $data['reference'] ?? null,
            );
        } catch (\InvalidArgumentException $e) {
            return redirect()->back()->withInput()->with('error', $e->getMessage());
        }

        Audit::log($me, 'JOURNAL_ENTRY_POSTED', 'JOURNAL_ENTRY', $entry->id, [
            'journal' => $entry->journal,
            'description' => $entry->description,
            'debit' => $entry->totalDebit(),
        ]);

        return redirect()->back()->with('success', __('gen.entryPosted'));
    }

    /**
     * POST /accounting/general/generate — retroactive generation from
     * history (idempotent: posted sources are skipped, §10).
     */
    public function generate(Request $request): RedirectResponse
    {
        /** @var User $me */
        $me = $request->user();

        $result = AccountingPostService::generateFromHistory($me);

        return redirect()->back()->with(
            'success',
            __('gen.generated', ['created' => $result['created'], 'skipped' => $result['skipped']])
        );
    }

    /**
     * GET /accounting/ledger/{id} — grand livre of one account (§6).
     */
    public function ledger(Request $request, string $id): View
    {
        $account = AccountingAccount::query()->findOrFail($id);

        return view('accounting.general.ledger', [
            'ledger' => AccountingPostService::generalLedger($account),
        ]);
    }

    /**
     * GET /accounting/balance — trial balance (balance, §6) + result.
     */
    public function balance(Request $request): View
    {
        $trial = AccountingPostService::trialBalance();

        // Résultat de l'exercice: revenues − expenses (accrual view).
        $revenue = round(collect($trial['rows'])->where('type', 'REVENUE')->sum('credit') -
            collect($trial['rows'])->where('type', 'REVENUE')->sum('debit'), 2);
        $expense = round(collect($trial['rows'])->where('type', 'EXPENSE')->sum('debit') -
            collect($trial['rows'])->where('type', 'EXPENSE')->sum('credit'), 2);

        return view('accounting.general.balance', [
            'trial' => $trial,
            'result' => ['revenue' => $revenue, 'expense' => $expense, 'net' => round($revenue - $expense, 2)],
        ]);
    }

    /**
     * POST /accounting/accounts — add a SYSCOHADA account to the chart
     * (Comptable; the seeded chart is the compact subset).
     */
    public function storeAccount(Request $request): RedirectResponse
    {
        $data = $request->validate([
            'code' => ['required', 'string', 'min:2', 'max:12', Rule::unique('accounting_accounts', 'code')],
            'name' => ['required', 'string', 'min:2', 'max:190'],
            'type' => ['required', 'string', Rule::in(Atelier::ACCOUNT_TYPES)],
        ]);

        $account = AccountingAccount::query()->create([
            'code' => $data['code'],
            'name' => $data['name'],
            'type' => $data['type'],
        ]);

        Audit::log($request->user(), 'JOURNAL_ENTRY_POSTED', 'ACCOUNTING_ACCOUNT', $account->id, [
            'code' => $account->code,
            'name' => $account->name,
            'type' => $account->type,
        ]);

        return redirect()->back()->with('success', __('gen.accountCreated'));
    }
}
